"""Balanced planset folds for cross-validating the stage-2 detector.

The single hold-out split evaluates on 31 images / 195 boxes / 5 plansets. That
is small enough that a mAP50 gap under ~0.05 cannot be told apart from noise,
which is exactly the position the imgsz sweep left us in. It also withholds 29%
of the labelled boxes from training permanently.

Rotating ``dataset.VAL_BUCKET`` would be the obvious way to get folds, and it
does not work: the hash buckets are badly unbalanced -- bucket 1 holds 2
plansets, 4 images and 17 boxes, which is not a val set. So folds are built here
by greedily bin-packing plansets into roughly equal *box* counts.

Two invariants the greedy pass must preserve, both load-bearing:

  * A planset never straddles train and val. A set repeats near-identical sheets,
    so a page-level split leaks and every score is inflated.
  * The five val folds are disjoint and together cover every planset, so each
    box is predicted exactly once across the campaign.

Nothing is re-exported and no source PDF is needed: the images and labels
already exist, only the list files differ.
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

FOLDS = 5


def _plansets(root: Path) -> dict[str, dict]:
    """Per-planset image list and box count, read from the exporter's index."""
    out: dict[str, dict] = {}
    with (root / "index.csv").open() as handle:
        for row in csv.DictReader(handle):
            entry = out.setdefault(row["planset"], {"images": [], "boxes": 0})
            entry["images"].append(row["image"])
            entry["boxes"] += int(row["boxes"])
    return out


def build_folds(plansets: dict[str, dict], folds: int = FOLDS) -> list[list[str]]:
    """Greedy longest-first bin-packing on box count.

    Sorting descending first matters: dropping the biggest plansets into the
    emptiest bin keeps the folds even, where insertion order alone would leave
    the last bin holding whatever is left.
    """
    bins: list[list[str]] = [[] for _ in range(folds)]
    loads = [0] * folds
    for key in sorted(plansets, key=lambda k: -plansets[k]["boxes"]):
        i = loads.index(min(loads))
        bins[i].append(key)
        loads[i] += plansets[key]["boxes"]
    return bins


def _write(dest: Path, root: Path, train: list[str], val: list[str]) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    # ABSOLUTE paths, exactly as train.overfit_gate does for the same reason:
    # ultralytics expands a leading "./" against the txt file's PARENT, and these
    # lists live one directory deeper than the dataset root, so "./images/..."
    # would resolve to cv/foldN/images/ and report "no labels found". An absolute
    # path still contains /images/, which is the separator ultralytics swaps for
    # /labels/ to find the annotations.
    for name, rows in (("train.txt", train), ("val.txt", val)):
        (dest / name).write_text(
            "".join(f"{(root / r).resolve()}\n" for r in rows)
        )
    # train:/val: stay RELATIVE -- ultralytics joins them onto path:, so an
    # absolute path here yields <root>/<root>/... and the dataset "disappears".
    (dest / "dataset.yaml").write_text(
        f"# Generated by make_folds.py. Do not edit.\n"
        f"path: {root.resolve()}\n"
        f"train: cv/{dest.name}/train.txt\n"
        f"val: cv/{dest.name}/val.txt\n"
        f"names:\n  0: window\n  1: door\n"
    )


def main(argv: list[str]) -> int:
    tag = argv[0] if argv else "v2"
    root = Path("out/dataset") / tag
    if not (root / "index.csv").exists():
        print(f"no dataset at {root}")
        return 1

    plansets = _plansets(root)
    folds = build_folds(plansets)
    cv = root / "cv"

    print(f"{len(plansets)} plansets -> {FOLDS} folds\n")
    seen: set[str] = set()
    for k, keys in enumerate(folds):
        val_imgs = [i for key in keys for i in plansets[key]["images"]]
        train_imgs = [i for key, v in plansets.items() if key not in keys
                      for i in v["images"]]
        boxes = sum(plansets[key]["boxes"] for key in keys)
        _write(cv / f"fold{k}", root, train_imgs, val_imgs)
        print(f"  fold{k}: val {len(keys)} plansets / {len(val_imgs):3} images / "
              f"{boxes:3} boxes   train {len(train_imgs):3} images")
        assert not (seen & set(keys)), "folds overlap"
        seen |= set(keys)
    assert seen == set(plansets), "folds do not cover every planset"

    # The shipped model: every planset trains. val mirrors train, so its score is
    # a training monitor and NOT a measurement -- the honest estimate for this
    # model is the cross-validated mean.
    every = [i for v in plansets.values() for i in v["images"]]
    _write(cv / "full", root, every, every)
    print(f"\n  full:  train on all {len(every)} images (val mirrors train, "
          f"so its score is NOT a held-out measurement)")
    print(f"\nwrote {cv}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
